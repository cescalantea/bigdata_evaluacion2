-- Preparacion de PostgreSQL local para Big Data Evaluacion 3.
--
-- 1) Cree una base llamada bigdata_eval3 desde pgAdmin o psql.
-- 2) Conectese a esa base.
-- 3) Ejecute este archivo completo.
--
-- La URI local esperada por el servidor es:
-- postgresql://USUARIO:CLAVE@127.0.0.1:5432/bigdata_eval3?sslmode=disable

CREATE TABLE IF NOT EXISTS public.estaciones (
    estacion_id INTEGER PRIMARY KEY,
    estacion_nombre VARCHAR(150) NOT NULL,
    latitud NUMERIC(8,4) NOT NULL CHECK (latitud BETWEEN -90 AND 90),
    longitud NUMERIC(8,4) NOT NULL CHECK (longitud BETWEEN -180 AND 180),
    zona_latitudinal VARCHAR(50) NOT NULL,
    area_cuenca_km2 NUMERIC(20,13) NOT NULL CHECK (area_cuenca_km2 >= 0)
);

CREATE TABLE IF NOT EXISTS public.mediciones_caudal (
    medicion_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    estacion_id INTEGER NOT NULL REFERENCES public.estaciones(estacion_id),
    fecha DATE NOT NULL,
    caudal_m3_s NUMERIC(10,3) NOT NULL CHECK (caudal_m3_s >= 0),
    CONSTRAINT uq_medicion_estacion_fecha UNIQUE (estacion_id, fecha)
);

CREATE INDEX IF NOT EXISTS ix_mediciones_fecha
    ON public.mediciones_caudal (fecha);

-- Comprobacion rapida del esquema.
SELECT table_schema, table_name
FROM information_schema.tables
WHERE table_schema = 'public'
  AND table_name IN ('estaciones', 'mediciones_caudal')
ORDER BY table_name;
